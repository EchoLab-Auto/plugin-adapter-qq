/// 表情 id → 中文名；`None` = 未知 id（新表情/扩展表情）。
pub fn face_name(id: &str) -> Option<&'static str> {
    let numeric: u32 = id.trim().parse().ok()?;
    FACES
        .binary_search_by_key(&numeric, |(face_id, _)| *face_id)
        .ok()
        .map(|index| FACES[index].1)
}

/// 渲染为可读标记：已知 id → `[表情:微笑]`；未知 id → `[表情:123]`。
pub fn face_marker(id: &str) -> String {
    match face_name(id) {
        Some(name) => format!("[表情:{name}]"),
        None => format!("[表情:{}]", id.trim()),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn table_is_sorted_and_unique() {
        // 二分查找依赖有序；重复 id 会造成静默取错名。
        for window in FACES.windows(2) {
            assert!(
                window[0].0 < window[1].0,
                "face table not strictly sorted at {:?}",
                window
            );
        }
    }

    #[test]
    fn known_ids_resolve_to_names() {
        assert_eq!(face_name("14"), Some("微笑"));
        assert_eq!(face_name("13"), Some("呲牙"));
        assert_eq!(face_name("0"), Some("惊讶"));
        // 高位段体现 id 空间：96 是「冷汗」、102/103 是「左/右哼哼」。
        assert_eq!(face_name("96"), Some("冷汗"));
        assert_eq!(face_name("103"), Some("右哼哼"));
        // 带空白也容忍（NapCat 一般不给，防御性处理）。
        assert_eq!(face_name(" 74 "), Some("太阳"));
    }

    #[test]
    fn unknown_ids_fall_back_to_marker_with_id() {
        assert_eq!(face_name("99999"), None);
        assert_eq!(face_marker("99999"), "[表情:99999]");
        assert_eq!(face_marker("not-a-number"), "[表情:not-a-number]");
    }

    #[test]
    fn known_id_marker_uses_name() {
        assert_eq!(face_marker("14"), "[表情:微笑]");
        assert_eq!(face_marker("103"), "[表情:右哼哼]");
    }
}
